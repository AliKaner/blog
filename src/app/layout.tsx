import type { Metadata, Viewport } from "next";
import {
  Cinzel,
  Cormorant_Garamond,
  IBM_Plex_Mono,
  Source_Serif_4,
} from "next/font/google";
import "./globals.css";
import { ConvexClientProvider } from "@/components/providers/ConvexClientProvider";
import { AdminSessionProvider } from "@/components/providers/AdminSessionProvider";
import { KonamiListener } from "@/components/admin/KonamiListener";
import { AdminLoginModal } from "@/components/admin/AdminLoginModal";
import { GrainOverlay } from "@/components/texture/GrainOverlay";
import { CornerDecor } from "@/components/texture/CornerDecor";
import { SiteNav } from "@/components/nav/SiteNav";
import { FaviconCycler } from "@/components/FaviconCycler";
import { CursorPicker } from "@/components/cursor/CursorPicker";
import { SITE_URL } from "@/lib/site";
import { AUTHOR } from "@/lib/seo";
import sectionMeta from "@/lib/sectionMeta.json";

// Type to match the Piranesi plates in the decor:
// headings in Roman inscription capitals (like the plate titles),
const cinzel = Cinzel({
  variable: "--font-cinzel",
  subsets: ["latin"],
});

// subtitles/accents in a Garamond italic (like the plate dedications),
const cormorant = Cormorant_Garamond({
  variable: "--font-cormorant",
  subsets: ["latin"],
  weight: ["500", "600"],
  style: ["italic"],
});

// and body text in a sturdy screen serif for comfortable reading.

const sourceSerif = Source_Serif_4({
  variable: "--font-source-serif",
  subsets: ["latin"],
});

const plexMono = IBM_Plex_Mono({
  variable: "--font-plex-mono",
  subsets: ["latin"],
  weight: ["400", "500"],
});

// Site-wide defaults. Pages set their own title/description/canonical (see
// src/lib/seo.ts); the share image comes from each segment's
// opengraph-image.png, generated by scripts/make-og.mjs.
export const metadata: Metadata = {
  metadataBase: new URL(SITE_URL),
  title: {
    default: `${AUTHOR} — Senior Fullstack Developer`,
    template: `%s · ${AUTHOR}`,
  },
  description: sectionMeta.home.description,
  applicationName: AUTHOR,
  authors: [{ name: AUTHOR, url: SITE_URL }],
  creator: AUTHOR,
  openGraph: {
    type: "website",
    siteName: AUTHOR,
    locale: "en_US",
  },
  twitter: { card: "summary_large_image" },
  robots: { index: true, follow: true },
};

export const viewport: Viewport = {
  themeColor: "#d3e1f1",
};

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html
      lang="en"
      className={`${cinzel.variable} ${cormorant.variable} ${sourceSerif.variable} ${plexMono.variable} h-full antialiased`}
    >
      <body className="min-h-full flex flex-col pr-20 md:pl-20 md:pr-0">
        <ConvexClientProvider>
          <AdminSessionProvider>
            <SiteNav />
            <main className="relative z-10 mx-auto w-full max-w-3xl flex-1 px-6 py-10 pb-24">
              {children}
            </main>
            <KonamiListener />
            <AdminLoginModal />
          </AdminSessionProvider>
        </ConvexClientProvider>
        <CornerDecor />
        <GrainOverlay />
        <FaviconCycler />
        <CursorPicker />
      </body>
    </html>
  );
}
